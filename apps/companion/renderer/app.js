'use strict';

/**
 * Renderer for the AvenqioPresence companion. It has no Node access: everything
 * goes through the `window.avenqio` bridge exposed by the preload script.
 */
const bridge = window.avenqio;
const $ = (id) => document.getElementById(id);

let snapshot = null;

function el(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}

function showError(message) {
  const node = $('global-error');
  if (!message) {
    node.hidden = true;
    node.textContent = '';
    return;
  }
  node.hidden = false;
  node.textContent = message;
}

function rpcLabel(rpc) {
  switch (rpc.status) {
    case 'connected':
      return 'Discord connected';
    case 'connecting':
      return 'Connecting…';
    case 'error':
      return 'Discord not running';
    default:
      return 'Discord offline';
  }
}

function renderPills(data) {
  const rpcPill = $('pill-rpc');
  rpcPill.className = `pill ${data.rpc.status === 'connected' ? 'ok' : data.rpc.status === 'error' ? 'error' : 'warn'}`;
  $('rpc-label').textContent = rpcLabel(data.rpc);

  const syncPill = $('pill-sync');
  const linked = data.linked;
  const failing = Boolean(data.sync.lastError);
  syncPill.className = `pill ${!linked ? 'warn' : failing ? 'error' : 'ok'}`;
  $('sync-label').textContent = !linked
    ? 'Not linked'
    : failing
      ? 'Sync error'
      : data.sync.lastSyncAt
        ? `Synced ${new Date(data.sync.lastSyncAt).toLocaleTimeString()}`
        : 'Syncing…';
}

function renderList(container, emptyNode, items, isActive, onSelect) {
  container.replaceChildren();
  emptyNode.hidden = items.length > 0;
  for (const item of items) {
    const row = el('li');
    if (isActive(item)) row.className = 'active';
    const left = el('div');
    left.append(el('p', 'name', item.label));
    left.append(el('p', 'meta', item.meta));
    const right = el('div');
    right.className = 'row';
    if (item.verified) right.append(el('span', 'badge verified', 'Verified'));
    if (isActive(item)) {
      right.append(el('span', 'badge', 'Published'));
    } else {
      const button = el('button', 'ghost small', 'Publish');
      button.type = 'button';
      button.addEventListener('click', async () => {
        button.disabled = true;
        const result = await onSelect(item);
        button.disabled = false;
        if (!result.ok) showError(result.error || 'Could not switch presence.');
        else showError(null);
      });
      right.append(button);
    }
    row.append(left, right);
    container.append(row);
  }
}

function render(data) {
  snapshot = data;
  $('version').textContent = `v${data.version}`;
  renderPills(data);

  const linked = data.linked && data.state;
  $('unlinked').hidden = Boolean(data.linked);
  $('linked').hidden = !linked;

  if (!data.linked) {
    $('api-url').value = data.settings.apiUrl;
    return;
  }
  if (!data.state) {
    showError(data.sync.lastError || 'Waiting for the dashboard to answer…');
  } else {
    showError(null);
  }

  const state = data.state;
  if (state) {
    $('avatar').src = state.account.avatarUrl || '';
    $('avatar').alt = state.account.displayName;
    $('account-name').textContent = state.account.displayName;
    $('account-discord').textContent = state.account.discord
      ? `@${state.account.discord.username} · device “${state.device.name}”`
      : `device “${state.device.name}”`;

    const activePresence = state.active.kind === 'presence' ? state.active.presenceId : null;
    const activePreset = state.active.kind === 'community_preset' ? state.active.presetId : null;
    const active = state.active.kind === 'none' ? null : state.active.label;
    $('active-name').textContent = active || 'Nothing published';
    $('active-meta').textContent =
      state.active.kind === 'community_preset'
        ? 'Community preset — edited centrally by your community, updates apply automatically.'
        : state.active.kind === 'presence'
          ? 'Personal presence from your dashboard.'
          : 'Activate a presence on the dashboard or publish one below.';

    const presences = state.presences.map((presence) => ({
      id: presence.id,
      label: presence.name,
      meta: `${presence.source === 'integration' ? 'Generated by an integration' : 'Manual configuration'}${
        presence.community ? ` · ${presence.community.name}` : ''
      }`,
      kind: 'presence',
    }));
    const presets = state.communityPresets.map((preset) => ({
      id: preset.id,
      label: preset.name,
      meta: preset.community.name,
      verified: preset.verified,
      kind: 'preset',
    }));

    $('presence-count').textContent = String(presences.length);
    $('preset-count').textContent = String(presets.length);

    renderList(
      $('presence-list'),
      $('presence-empty'),
      presences,
      (item) => item.id === activePresence,
      (item) => bridge.select({ presenceId: item.id, presetId: null }),
    );
    renderList(
      $('preset-list'),
      $('preset-empty'),
      presets,
      (item) => item.id === activePreset,
      (item) => bridge.select({ presenceId: null, presetId: item.id }),
    );
  }

  const settings = data.settings;
  $('opt-autopublish').checked = settings.autoPublish;
  $('opt-start').checked = settings.startWithWindows;
  $('opt-tray').checked = settings.minimizeToTray;
  $('opt-updates').checked = settings.autoUpdates;
  $('api-url').value = settings.apiUrl;

  if (data.update) {
    const update = data.update;
    $('update-status').textContent =
      update.status === 'available'
        ? `Version ${update.version} is available.`
        : update.status === 'current'
          ? 'You are running the latest version.'
          : update.status === 'not-configured'
            ? 'Automatic updates are not configured for this build — download the newest installer from the dashboard.'
            : `Update check failed: ${update.message}`;
  }

  const logsNode = $('logs');
  if (!logsNode.hidden) {
    logsNode.textContent = data.logs.join('\n');
    logsNode.scrollTop = logsNode.scrollHeight;
  }
}

async function boot() {
  render(await bridge.snapshot());
  bridge.onSnapshot(render);
}

$('link-form').addEventListener('submit', async (event) => {
  event.preventDefault();
  const error = $('link-error');
  error.hidden = true;
  const code = $('pairing-code').value.trim();
  const button = $('link-button');
  button.disabled = true;
  button.textContent = 'Linking…';
  const result = await bridge.link(code);
  button.disabled = false;
  button.textContent = 'Link device';
  if (!result.ok) {
    error.hidden = false;
    error.textContent = result.error || 'Pairing failed.';
    return;
  }
  $('pairing-code').value = '';
});

$('save-api').addEventListener('click', async () => {
  const next = await bridge.updateSettings({ apiUrl: $('api-url').value.trim() });
  render(next);
  showError('Connection URL saved. Link the device again if it was paired elsewhere.');
});

$('clear').addEventListener('click', async () => {
  const result = await bridge.select({ presenceId: null, presetId: null });
  if (!result.ok) showError(result.error || 'Could not clear the presence.');
});

$('refresh').addEventListener('click', async () => {
  const result = await bridge.refresh();
  if (!result.ok) showError(result.error || 'Sync failed.');
});

for (const [id, key] of [
  ['opt-autopublish', 'autoPublish'],
  ['opt-start', 'startWithWindows'],
  ['opt-tray', 'minimizeToTray'],
  ['opt-updates', 'autoUpdates'],
]) {
  $(id).addEventListener('change', async (event) => {
    render(await bridge.updateSettings({ [key]: event.target.checked }));
  });
}

$('check-updates').addEventListener('click', async () => {
  $('update-status').textContent = 'Checking…';
  const result = await bridge.checkForUpdates();
  if (result.status === 'available') {
    $('update-status').textContent = `Version ${result.version} is available — opening the download page.`;
    await bridge.openExternal(result.url);
  } else if (result.status === 'current') {
    $('update-status').textContent = 'You are running the latest version.';
  } else if (result.status === 'not-configured') {
    $('update-status').textContent =
      'Automatic updates are not configured for this build — download the newest installer from the dashboard.';
  } else {
    $('update-status').textContent = `Update check failed: ${result.message}`;
  }
});

$('unlink').addEventListener('click', async () => {
  await bridge.unlink();
  showError(null);
});

$('toggle-logs').addEventListener('click', () => {
  const logsNode = $('logs');
  logsNode.hidden = !logsNode.hidden;
  $('toggle-logs').textContent = logsNode.hidden ? 'Show' : 'Hide';
  if (!logsNode.hidden && snapshot) {
    logsNode.textContent = snapshot.logs.join('\n');
    logsNode.scrollTop = logsNode.scrollHeight;
  }
});

$('quit').addEventListener('click', () => bridge.quit());

boot().catch((error) => showError(String(error)));
